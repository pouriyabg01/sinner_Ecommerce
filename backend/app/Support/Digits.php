<?php

namespace App\Support;

/**
 * کدهایی که مشتری تایپ می‌کند (کد سفارش، کد پیگیری، کد رهگیری) با ارقام انگلیسی
 * ذخیره می‌شوند؛ ورودیِ کیبورد فارسی یا عربی قبل از جست‌وجو و ذخیره یکدست می‌شود.
 */
class Digits
{
    public static function english(string $value): string
    {
        return strtr($value, [
            '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
            '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
            '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
            '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        ]);
    }

    /** مبلغ داخل پیام‌های سرور: سه‌رقم‌سه‌رقم و با ارقام فارسی، دقیقاً مثل قیمت‌های خود سایت */
    public static function money(int $value): string
    {
        return strtr(number_format($value), [
            '0' => '۰', '1' => '۱', '2' => '۲', '3' => '۳', '4' => '۴',
            '5' => '۵', '6' => '۶', '7' => '۷', '8' => '۸', '9' => '۹',
        ]);
    }

    /** کد سفارش یا تعمیر: ارقام انگلیسی، حروف بزرگ، بدون فاصله‌ی اضافه */
    public static function code(string $value): string
    {
        return strtoupper(trim(static::english($value)));
    }
}
