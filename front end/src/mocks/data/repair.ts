export function getIssue(id: string) {
  return commonIssues.find((i) => i.id === id)
}

export function estimateCost(issueIds: string[]) {
  const picked = issueIds.map(getIssue).filter(Boolean) as CommonIssue[]
  if (!picked.length) return { min: 0, max: 0, days: 0 }
  return {
    min: picked.reduce((s, i) => s + i.estimatedMin, 0),
    max: picked.reduce((s, i) => s + i.estimatedMax, 0),
    days: Math.max(...picked.map((i) => i.estimatedDays)),
  }
}

